// ContextType classifies the semantic role of a KV cache block in an agent program.
// Higher context-weight blocks have lower reuse value and are more aggressively evicted
// under the weighted-eviction policy (Issue #1828 §3).
type ContextType string

const (
	// ContextTypeUnknown indicates the context type was not specified.
	ContextTypeUnknown ContextType = ""

	// ContextTypeSystemPrompt marks blocks that belong to the agent's system prompt
	// and role instructions. These span thousands of tokens and are shared across
	// every session of the same agent program — highest durable value.
	ContextTypeSystemPrompt ContextType = "system_prompt"

	// ContextTypeToolDef marks blocks that describe tool schemas, APIs, or function
	// definitions attached to the agent. Also program-level and session-invariant.
	ContextTypeToolDef ContextType = "tool_def"

	// ContextTypeConversation marks incremental dialogue history between the user
	// and the agent. Accumulates across a session with moderate reuse value.
	ContextTypeConversation ContextType = "conversation"

	// ContextTypeReasoning marks scratch-pad / chain-of-thought intermediate blocks
	// generated by the agent during inference. Single-use and near-zero reuse value.
	ContextTypeReasoning ContextType = "reasoning"
)

// Valid reports whether t is one of the known ContextType values.
func (t ContextType) Valid() bool {
	switch t {
	case ContextTypeSystemPrompt, ContextTypeToolDef,
		ContextTypeConversation, ContextTypeReasoning,
		ContextTypeUnknown:
		return true
	}
	return false
}

// DefaultContextWeight returns the eviction weight factor for this context type.
// The weighted-eviction formula is eviction_score = access_recency_score * context_weight / priority.
// Lower weights make blocks less likely to be evicted (more durable).
//
//	system_prompt = 0.1  (most durable)
//	tool_def      = 0.2
//	conversation  = 1.0  (baseline)
//	reasoning     = 2.0  (most disposable)
//	unknown       = 1.0  (baseline, matches LRU behaviour)
func (t ContextType) DefaultContextWeight() float64 {
	switch t {
	case ContextTypeSystemPrompt:
		return 0.1
	case ContextTypeToolDef:
		return 0.2
	case ContextTypeConversation:
		return 1.0
	case ContextTypeReasoning:
		return 2.0
	default:
		return 1.0
	}
}

// String implements fmt.Stringer.
func (t ContextType) String() string { return string(t) }

// AgentHints carries agent-semantic fields that are optionally propagated through
// the Kthena data plane (RFC Issue #1828 §1). All fields are optional. Legacy
// components and engines silently ignore them — the stack falls back to pure
// hash-based KV-aware routing when hints are absent.
type AgentHints struct {
	// ProgramID is an opaque identifier for the agent program template
	// (e.g. the UUID of an `agent.yaml` CRD or a fully qualified `domain/agent` name).
	// Router plugins use it for program-level affinity scoring.
	ProgramID string `json:"program_id,omitempty"`

	// TaskPriority is the numeric priority tier of the request.
	// Higher values mean higher priority. Default 0 maps to baseline fairness.
	TaskPriority int `json:"task_priority,omitempty"`

	// ContextType identifies the semantic role of the incoming request in the
	// agent program. Used by the runtime-sidecar weighted-eviction logic.
	ContextType ContextType `json:"context_type,omitempty"`

	// SpeculativePrefill tells the PD disaggregation scheduler to proactively
	// pre-warm the next turn's prefix on an idle Prefill pod once this decode
	// completes. Disabled by default.
	SpeculativePrefill bool `json:"speculative_prefill,omitempty"`

	// SessionTTLHint seconds is the suggested time-to-live for session-aligned
	// cache pinning. A value <= 0 disables pinning.
	SessionTTLHint int `json:"session_ttl_hint,omitempty"`

	// SessionID is the agent session identifier used for cache pinning.
	// When combined with an open/heartbeat/close session lifecycle signal,
	// the router pins the session's KV blocks during idle windows.
	SessionID string `json:"session_id,omitempty"`

	// AgentVersion optionally identifies which version of the agent program
	// generated these hints. Useful for observability and for future
	// multi-version colocation policies.
	AgentVersion string `json:"agent_version,omitempty"`
}

// IsEmpty reports whether no agent-semantic fields were supplied.
// An empty hint means "behave exactly as before — pure hash-based routing".
func (h *AgentHints) IsEmpty() bool {
	if h == nil {
		return true
	}
	return h.ProgramID == "" &&
		h.TaskPriority == 0 &&
		h.ContextType == ContextTypeUnknown &&
		!h.SpeculativePrefill &&
		h.SessionTTLHint <= 0 &&
		h.SessionID == "" &&
		h.AgentVersion == ""
}

// DefaultPriority returns TaskPriority with a zero-value fallback of 1 (baseline).
func (h *AgentHints) DefaultPriority() int {
	if h == nil || h.TaskPriority <= 0 {
		return 1
	}
	return h.TaskPriority
}

// DefaultSessionTTL returns SessionTTLHint with a zero-value fallback of 60 seconds.
func (h *AgentHints) DefaultSessionTTL() int {
	if h == nil || h.SessionTTLHint <= 0 {
		return 60
	}
	return h.SessionTTLHint
}

// HasProgramAffinity reports whether the request carries enough information
// to participate in program-level affinity routing.
func (h *AgentHints) HasProgramAffinity() bool {
	return h != nil && h.ProgramID != ""
}

// HasSessionPinning reports whether the request carries session pinning info.
func (h *AgentHints) HasSessionPinning() bool {
	return h != nil && h.SessionID != ""
}

// Equal compares two hints for semantic equality (useful for tests).
func (h *AgentHints) Equal(other *AgentHints) bool {
	if h == nil && other == nil {
		return true
	}
	if h == nil || other == nil {
		return false
	}
	return h.ProgramID == other.ProgramID &&
		h.TaskPriority == other.TaskPriority &&
		h.ContextType == other.ContextType &&
		h.SpeculativePrefill == other.SpeculativePrefill &&
		h.SessionTTLHint == other.SessionTTLHint &&
		h.SessionID == other.SessionID &&
		h.AgentVersion == other.AgentVersion
}

// String produces a compact human-readable representation.
func (h *AgentHints) String() string {
	if h == nil {
		return "AgentHints(nil)"
	}
	return fmt.Sprintf("AgentHints{program=%q, priority=%d, ctx=%s, speculative=%v, ttl=%d, session=%q, version=%q}",
		h.ProgramID, h.TaskPriority, h.ContextType, h.SpeculativePrefill,
		h.SessionTTLHint, h.SessionID, h.AgentVersion)
}

// Marshal serializes the hints to JSON — the format written to Redis trailing
// fields and appended to KV events by the runtime sidecar (RFC §1).
func (h *AgentHints) Marshal() (string, error) {
	if h == nil || h.IsEmpty() {
		return "", nil
	}
	b, err := json.Marshal(h)
	if err != nil {
		return "", fmt.Errorf("marshal AgentHints: %w", err)
	}
	return string(b), nil
}

// UnmarshalAgentHints parses the JSON representation written by Marshal.
// Unknown fields are silently dropped — this keeps the decoder forward-compatible
// with future hint extensions.
func UnmarshalAgentHints(raw string) (*AgentHints, error) {
	if strings.TrimSpace(raw) == "" {
		return nil, nil
	}
	var h AgentHints
	if err := json.Unmarshal([]byte(raw), &h); err != nil {
		return nil, fmt.Errorf("unmarshal AgentHints: %w", err)
	}
	if h.IsEmpty() {
		return nil, nil
	}
	return &h, nil
}

// --- Header parsing helpers ------------------------------------------------

// AgentHintsHeaderName is the canonical HTTP header from which the router
// extracts agent hints at the request entry point. The header value is a JSON
// object matching AgentHints.
const AgentHintsHeaderName = "X-Kthena-Agent-Hints"

// parseHeaderKV parses a single "key=value" token, allowing optional quotes.
// Used by ParseAgentHintsFromHeader as a tolerant fallback when callers embed
// hints as a comma-separated list instead of JSON.
func parseHeaderKV(token string) (key, value string, ok bool) {
	idx := strings.Index(token, "=")
	if idx < 0 {
		return "", "", false
	}
	key = strings.TrimSpace(token[:idx])
	value = strings.TrimSpace(token[idx+1:])
	value = strings.Trim(value, "\"")
	if key == "" {
		return "", "", false
	}
	return key, value, true
}

// ParseAgentHintsFromHeader attempts to decode the raw value of AgentHintsHeaderName.
// It first tries JSON. On failure it falls back to a simple comma-separated
// key=value form. Unknown keys are silently ignored to maintain forward compatibility.
//
// JSON example:
//
//	{"program_id":"code-agent/v2","task_priority":5,"session_id":"sess-123","context_type":"system_prompt"}
//
// KV fallback example:
//
//	program_id=code-agent/v2,task_priority=5,session_id=sess-123
func ParseAgentHintsFromHeader(raw string) (*AgentHints, error) {
	if strings.TrimSpace(raw) == "" {
		return nil, nil
	}

	// Fast path: valid JSON.
	if strings.HasPrefix(strings.TrimSpace(raw), "{") {
		h, err := UnmarshalAgentHints(raw)
		if err == nil {
			return h, nil
		}
		// fall through to KV fallback
	}

	h := &AgentHints{}
	for _, token := range strings.Split(raw, ",") {
		key, value, ok := parseHeaderKV(token)
		if !ok {
			continue
		}
		switch strings.ToLower(key) {
		case "program_id", "programid":
			h.ProgramID = value
		case "task_priority", "priority":
			if n, err := strconv.Atoi(value); err == nil {
				h.TaskPriority = n
			}
		case "context_type", "contexttype":
			ct := ContextType(value)
			if ct.Valid() {
				h.ContextType = ct
			}
		case "speculative_prefill", "speculativeprefill":
			b, err := strconv.ParseBool(value)
			if err == nil {
				h.SpeculativePrefill = b
			}
		case "session_ttl_hint", "sessionttlhint", "session_ttl", "ttl":
			if n, err := strconv.Atoi(value); err == nil {
				h.SessionTTLHint = n
			}
		case "session_id", "sessionid":
			h.SessionID = value
		case "agent_version", "agentversion":
			h.AgentVersion = value
		}
	}

	if h.IsEmpty() {
		return nil, nil
	}
	return h, nil
}
